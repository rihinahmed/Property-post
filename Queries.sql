-- Seller table from users
create table sellers (
   seller_id  number
      generated by default as identity
   primary key,
   user_id    number unique not null,
   shop_name  varchar2(100),
   phone      varchar2(20),
   address    varchar2(255),
   created_at date default sysdate,
   constraint fk_sellers_user foreign key ( user_id )
      references users ( id )
         on delete cascade
);

-- Property table
create table properties (
   id          number
      generated by default as identity
   primary key,
   seller_id   number not null,
   title       varchar2(255),
   rent        number,
   description clob,
   amenities   clob,
   pros        clob,
   cons        clob,
   images      clob,
   location    locationn,
   created_at  date default sysdate,
   status      varchar2(50) default 'active' not null,
   saved_count number default 0 not null,
   views       number default 0 not null,
   constraint fk_properties_seller foreign key ( seller_id )
      references users ( id )
         on delete cascade
);

create table saved_rooms (
   user_id  number not null,
   room_id  number not null,
   saved_at date default sysdate,
   primary key ( user_id,
                 room_id ),
   constraint fk_savedrooms_user foreign key ( user_id )
      references users ( id )
         on delete cascade,
   constraint fk_savedrooms_room foreign key ( room_id )
      references properties ( id )
         on delete cascade
);

