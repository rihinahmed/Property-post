-- USERS table
create table users (
   id            number
      generated by default as identity
   primary key,
   name          varchar2(100) not null,
   email         varchar2(100) not null unique,
   password_hash varchar2(255) not null,
   role          varchar2(20) not null,
   full_name     varchar2(100),
   nid_photo     clob,
   phone         varchar2(20),
   address       varchar2(500),
   occupation    varchar2(100),
   profile_img   varchar2(255),
   bio           varchar2(2000)
);

-- Rooms table (first version)
create table rooms (
   id          number
      generated by default as identity
   primary key,
   user_id     number not null,
   title       varchar2(100),
   description varchar2(500),
   listed_date date default sysdate,
   constraint fk_rooms_user foreign key ( user_id )
      references users ( id )
         on delete cascade
);

-- Blog post table from user
create table blog_posts (
   id         number
      generated by default as identity
   primary key,
   user_id    number not null,
   title      varchar2(200),
   content    clob,
   created_at date default sysdate,
   constraint fk_blogposts_user foreign key ( user_id )
      references users ( id )
         on delete cascade
);

-- Messages table (latest version, after drop/recreate)
create table messages (
   id           number
      generated by default on null as identity
   primary key,
   sender_id    number not null,
   recipient_id number not null,
   message_text clob not null,
   sent_at      timestamp with time zone default current_timestamp not null,
   constraint fk_sender foreign key ( sender_id )
      references users ( id )
         on delete cascade,
   constraint fk_recipient foreign key ( recipient_id )
      references users ( id )
         on delete cascade
);

-- Announcement table
create table announcements (
   id        number
      generated by default as identity
   primary key,
   title     varchar2(255) not null,
   content   clob not null,
   posted_by varchar2(100),
   posted_at timestamp default current_timestamp
);

